"""Regenerates Artemis/models/IconKeywords.swift: search keywords for every icon
in SFSymbols.swift and Emojis.swift, from Apple's SF Symbols search keywords
(on-device CoreGlyphs) and Unicode CLDR English emoji annotations.

usage: tools/icon-keywords.py  (fetches CLDR from GitHub)
"""
import plistlib, re, sys, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / "Artemis/models"
GLYPHS = Path("/System/Library/CoreServices/CoreGlyphs.bundle/Contents/Resources")
CLDR = "https://raw.githubusercontent.com/unicode-org/cldr/main/common/{}/en.xml"

def words(s):
    return [w for w in re.split(r"[^a-z0-9]+", s.lower()) if len(w) > 1]

symbols_src = (MODELS / "SFSymbols.swift").read_text().split("static let categories", 1)[1]
symbols = list(dict.fromkeys(re.findall(r'"([a-z0-9.]+)"', symbols_src)))
emoji = re.findall(r'Entry\(glyph: "([^"]+)", name: "([^"]+)"\)', (MODELS / "Emojis.swift").read_text())

search = plistlib.loads((GLYPHS / "symbol_search.plist").read_bytes())
aliases = plistlib.loads((GLYPHS / "name_aliases.strings").read_bytes())

annotations = {}
for kind in ("annotations", "annotationsDerived"):
    xml = urllib.request.urlopen(CLDR.format(kind)).read().decode()
    for cp, text in re.findall(r'<annotation cp="([^"]+)">([^<]+)</annotation>', xml):
        annotations[cp] = text

def row(icon, name, tags):
    seen = set(words(name))
    fresh = [w for t in tags for w in words(t) if not (w in seen or seen.add(w))]
    return f"{icon}\t{' '.join(fresh)}" if fresh else None

rows = [row(s, s, search.get(s) or search.get(aliases.get(s, s), [])) for s in symbols]
missing = []
for glyph, name in emoji:
    text = annotations.get(glyph) or annotations.get(glyph.replace("️", ""))
    if text is None:
        missing.append(glyph)
    rows.append(row(glyph, name, (text or "").split("|")))
rows = [r for r in rows if r]
if any('"""' in r or "\\" in r for r in rows):
    sys.exit("a keyword would break the string literal")

out = MODELS / "IconKeywords.swift"
out.write_text(
    "// generated by tools/icon-keywords.py — do not edit\n\n"
    "nonisolated enum IconKeywords {\n"
    "    /// icon<TAB>space-separated keywords beyond the icon's own name words\n"
    "    static let table = \"\"\"\n" + "\n".join(rows) + '\n"""\n}\n')
print(f"{out.relative_to(ROOT)}: {len(rows)} rows; emoji without CLDR keywords: {''.join(missing)}")
